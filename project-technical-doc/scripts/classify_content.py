#!/usr/bin/env python3
"""Generate content-index.json v1: classify figures/tables/modules for a website.

The index is a *classification sidecar* only.  It never replaces the original
Markdown tables/diagrams and never renders a website.  A downstream website can
group/filter cards by ``category`` / ``group_id`` while still reading the full
content from the technical Markdown.

Contract highlights
-------------------
* items: table / diagram / module, each with stable id, chapter/section,
  line range, category, group_id, group_title, content_sha256
* groups: one entry per similarity group, item_ids and count
* coverage: every Markdown table, Mermaid block and physical-module section is
  represented exactly once; missing/extra items make the checker FAIL

Usage:
  python scripts/classify_content.py <technical.md> [--out content-index.json]
                                      [--report classification-report.json]
"""
from __future__ import annotations

import sys as _sys
if hasattr(_sys.stdout, "reconfigure"):
    _sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(_sys.stderr, "reconfigure"):
    _sys.stderr.reconfigure(encoding="utf-8", errors="replace")

import argparse
import json
import re
from collections import Counter, OrderedDict
from pathlib import Path

import content_rules as rules

SCHEMA_VERSION = 1
SKILL_NAME = "project-technical-doc"
KIND_PREFIX = {"table": "TBL", "diagram": "FIG", "module": "MOD"}
ALLOWED_KINDS = tuple(KIND_PREFIX)
ALLOWED_CATEGORIES = (
    "data-structure", "protocol", "interface-pin", "parameter-config",
    "flow", "architecture", "test", "specification", "function", "schedule",
    "technology", "appendix", "excluded", "hardware-resource", "terminology",
    "index", "materials", "other-table", "other",
    "sensor", "actuator", "display", "input", "communication",
)


def split_row(line):
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|"):
        s = s[:-1]
    return [c.strip() for c in s.split("|")]


def is_separator(line):
    if "|" not in line:
        return False
    cells = split_row(line)
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", c.replace(" ", "")) for c in cells)


def parse_tables(lines):
    tables = []
    i = 0
    while i < len(lines) - 1:
        if lines[i].strip().startswith("|") and is_separator(lines[i + 1]):
            start = i
            end = i + 1
            while end + 1 < len(lines) and lines[end + 1].strip().startswith("|"):
                end += 1
            headers = split_row(lines[i])
            rows = [split_row(x) for x in lines[i + 2:end + 1] if x.strip().startswith("|")]
            tables.append({
                "line_start": start + 1,
                "line_end": end + 1,
                "headers": headers,
                "rows": rows,
                "text": "\n".join(lines[start:end + 1]),
            })
            i = end + 1
        else:
            i += 1
    return tables


def parse_diagrams(lines):
    diagrams = []
    i = 0
    while i < len(lines):
        if lines[i].strip().lower() in ("```mermaid", "``` mermaid"):
            j = i + 1
            while j < len(lines) and not lines[j].strip().startswith("```"):
                j += 1
            content = "\n".join(lines[i + 1:j])
            diagrams.append({
                "line_start": i + 1,
                "line_end": min(j + 1, len(lines)),
                "content": content,
                "text": "\n".join(lines[i:min(j + 1, len(lines))]),
            })
            i = j + 1
        else:
            i += 1
    return diagrams


def parse_modules(lines, base_dir=None):
    # Prefer the fixed sidecar generated by gen_physical_modules.py so the
    # website sees the same individual hardware modules (D1/SHT40/...), not
    # only the functional H3 groups.
    if base_dir:
        sidecar = Path(base_dir) / "physical-modules.json"
        if sidecar.is_file():
            try:
                data = json.loads(sidecar.read_text("utf-8"))
                out = []
                for m in data.get("modules", []):
                    if not isinstance(m, dict):
                        continue
                    code = str(m.get("code", "")).strip()
                    name = str(m.get("name", "")).strip()
                    if not code or not name:
                        continue
                    title = name if code.casefold() in name.casefold() else f"{code} {name}"
                    out.append({
                        "line_start": int(m.get("section_line") or 0),
                        "line_end": int(m.get("section_line") or 0),
                        "title": title,
                        "section": m.get("section") or title,
                        "code": code,
                        "category": m.get("category") or "other",
                        "text": " ".join(str(m.get(k, "")) for k in ("hardware", "note")),
                    })
                if out:
                    return out
            except (OSError, ValueError, json.JSONDecodeError):
                pass
    sections = rules.module_sections(lines)
    if sections is None:
        return []
    marks = rules.heading_marks(lines)
    modules = []
    for pos, (line_no, title) in enumerate(sections):
        end_idx = len(lines)
        for idx, level, _ in marks:
            if idx + 1 > line_no and level <= 3:
                end_idx = idx
                break
        body = "\n".join(lines[line_no:end_idx])
        if rules.is_software_section(title, body):
            continue
        category = rules.classify_physical(title, body)
        if category is None:
            continue
        code = rules.best_code_token(title)
        modules.append({
            "line_start": line_no,
            "line_end": max(line_no, end_idx),
            "title": rules.strip_number(title),
            "section": rules.strip_number(title),
            "code": code,
            "category": category,
            "text": body,
        })
    return modules

def _title_and_context(lines, line_start):
    marks = rules.heading_marks(lines)
    h2, h3, h4 = rules.nearest_heading(marks, line_start - 1)
    title = h4 or h3 or h2 or "未命名内容"
    title = rules.strip_number(title)
    section = rules.strip_number(h3) if h3 else ""
    chapter = rules.strip_number(h2) if h2 else ""
    return title, chapter, section


def _local_table_title(lines, line_start):
    """Nearest H4/H3, never the H2 chapter: chapter names must not classify tables."""
    marks = rules.heading_marks(lines)
    _h2, h3, h4 = rules.nearest_heading(marks, line_start - 1)
    return rules.strip_number(h4 or h3 or "")


def _caption_near(lines, line_start, line_end, marker):
    for idx in (line_start - 2, line_end):
        if 0 <= idx < len(lines):
            text = lines[idx].strip()
            if text.startswith(marker):
                return re.sub(r"\s+", " ", text)[:120]
    return ""


def _group_for(item):
    kind, cat = item["kind"], item["category"]
    title = item.get("title", "")
    code = item.get("module_code") or ""
    if kind == "module":
        return rules.CATEGORY_CN.get(cat, "其他实物模块"), f"module-{cat}"
    def usable_code(value):
        return value if value and any(ch.isascii() and (ch.isalnum() or ch in "+-_.") for ch in value) else ""

    if kind == "table":
        if cat == "data-structure":
            label = usable_code(code)
            return (f"{label} 数据结构" if label else "数据结构"), f"data-{label or 'general'}"
        if cat == "protocol":
            label = usable_code(code)
            return (f"{label} 通信协议" if label else "通信协议"), f"protocol-{label or 'general'}"
        if cat == "parameter-config":
            label = usable_code(code)
            return (f"{label} 参数与配置" if label else "参数与配置"), f"param-{label or 'general'}"
        if cat == "hardware-resource":
            label = usable_code(code)
            return (f"{label} 硬件资源" if label else "硬件资源与分配"), f"hardware-{label or 'general'}"
        if cat == "interface-pin":
            label = usable_code(code)
            return (f"{label} 引脚与接口" if label else "引脚与接口"), f"pin-{label or 'general'}"
        labels = {
            "architecture": "架构与组成",
            "flow": "状态与流程",
            "test": "测试与结果",
            "specification": "规格与选型",
            "function": "功能与场景",
            "schedule": "任务与调度",
            "technology": "技术说明",
            "terminology": "术语与定义",
            "index": "索引与目录",
            "materials": "资料与参考",
            "appendix": "附录与速查",
            "excluded": "已排除章节（不应展示）",
            "other-table": "其他数据表",
        }
        if cat in labels:
            return labels[cat], f"{cat}"
        return "其他数据表", "other-table"
    # diagram
    if cat == "architecture":
        return "架构与组成", "architecture"
    if cat == "flow":
        return "流程图", "flow"
    return "其他图示", "other-diagram"

def build_index(md_path):
    md = Path(md_path).expanduser().resolve()
    text = md.read_text("utf-8-sig")
    lines = text.splitlines()
    raw = []
    for t in parse_tables(lines):
        title, chapter, section = _title_and_context(lines, t["line_start"])
        caption = _caption_near(lines, t["line_start"], t["line_end"], "表")
        local_title = _local_table_title(lines, t["line_start"])
        if any(word in (chapter or "") for word in ("已知问题", "改进建议", "风险与对策", "未来展望", "后续规划")):
            cat = "excluded"
        else:
            cat = rules.classify_table(t["headers"], local_title, caption)
        code = rules.module_code_from_text(title + " " + " ".join(t["headers"]))
        raw.append({
            "kind": "table", "title": title, "chapter": chapter, "section": section,
            "line_start": t["line_start"], "line_end": t["line_end"],
            "category": cat, "module_code": code,
            "headers": t["headers"], "row_count": len(t["rows"]),
            "caption": caption,
            "content_sha256": rules.sha256_text(t["text"]),
            "keywords": rules.extract_keywords(title + " " + " ".join(t["headers"]) + " " + t["text"]),
        })
    for d in parse_diagrams(lines):
        title, chapter, section = _title_and_context(lines, d["line_start"])
        cat = rules.classify_diagram(d["content"], title)
        raw.append({
            "kind": "diagram", "title": title, "chapter": chapter, "section": section,
            "line_start": d["line_start"], "line_end": d["line_end"],
            "category": cat, "module_code": rules.module_code_from_text(title + " " + d["content"]),
            "caption": _caption_near(lines, d["line_start"], d["line_end"], "图"),
            "content_sha256": rules.sha256_text(d["content"]),
            "keywords": rules.extract_keywords(title + " " + d["content"]),
        })
    for m in parse_modules(lines, md.parent):
        raw.append({
            "kind": "module", "title": m["title"], "chapter": "模块详解",
            "section": m["section"], "line_start": m["line_start"], "line_end": m["line_end"],
            "category": m["category"], "module_code": m["code"],
            "content_sha256": rules.sha256_text(m["text"]),
            "keywords": rules.extract_keywords(m["title"] + " " + m["text"]),
            "caption": "",
        })
    raw.sort(key=lambda x: (x["line_start"], 0 if x["kind"] == "table" else 1 if x["kind"] == "diagram" else 2))
    counters = Counter()
    for item in raw:
        counters[item["kind"]] += 1
        item["id"] = f"{KIND_PREFIX[item['kind']]}-{counters[item['kind']]:03d}"
        group_title, group_key = _group_for(item)
        item["group_id"] = rules.stable_group_id(group_title)
        item["group_title"] = group_title
    groups = OrderedDict()
    for item in raw:
        g = groups.setdefault(item["group_id"], {
            "id": item["group_id"], "title": item["group_title"],
            "category": item["category"], "item_ids": [], "count": 0,
            "first_line": item["line_start"],
        })
        g["item_ids"].append(item["id"])
        g["count"] += 1
    group_list = sorted(groups.values(), key=lambda g: (g["first_line"], g["title"]))
    for g in group_list:
        g.pop("first_line", None)
    summary = {
        "items": len(raw),
        "tables": counters["table"],
        "diagrams": counters["diagram"],
        "modules": counters["module"],
        "groups": len(group_list),
        "by_category": dict(Counter(x["category"] for x in raw)),
    }
    dup = [h for h, c in Counter(x["content_sha256"] for x in raw).items() if c > 1]
    warnings = []
    if dup:
        warnings.append(f"存在 {len(dup)} 组完全相同内容哈希；已保留每条记录，网站可按 content_sha256 去重")
    for item in raw:
        if item["kind"] == "table" and not item.get("headers"):
            warnings.append(f"{item['id']} 未解析到表头")
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_by": SKILL_NAME,
        "source_md": md.name,
        "source_md_sha256": rules.sha256_text(text),
        "items": raw,
        "groups": group_list,
        "summary": summary,
        "warnings": warnings,
    }


def check_content_index(md_path, index_path=None):
    md = Path(md_path).expanduser().resolve()
    index = Path(index_path) if index_path else md.parent / "content-index.json"
    errors, warnings = [], []
    report = {"status": "FAIL", "markdown": str(md), "index": str(index),
              "items": 0, "groups": 0, "errors": errors, "warnings": warnings}
    if not index.is_file():
        errors.append(f"缺少分类索引 {index.name}：必须与技术文档 MD 同级交付")
        return report
    try:
        data = json.loads(index.read_text("utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        errors.append(f"{index.name} 无法解析：{exc}")
        return report
    if data.get("schema_version") != SCHEMA_VERSION:
        errors.append(f"schema_version 必须为 {SCHEMA_VERSION}")
    if data.get("generated_by") != SKILL_NAME:
        errors.append(f"generated_by 必须为 {SKILL_NAME}")
    text = md.read_text("utf-8-sig")
    if data.get("source_md_sha256") and data["source_md_sha256"] != rules.sha256_text(text):
        errors.append("source_md_sha256 与当前技术文档不一致：请重新生成分类索引")
    items = data.get("items")
    if not isinstance(items, list):
        errors.append("items 必须是数组")
        return report
    groups = data.get("groups")
    if not isinstance(groups, list):
        errors.append("groups 必须是数组")
        return report
    report["items"], report["groups"] = len(items), len(groups)
    seen = set()
    group_ids = set()
    for g in groups:
        if not isinstance(g, dict) or not g.get("id"):
            errors.append("每个分组必须有 id")
            continue
        if g["id"] in group_ids:
            errors.append(f"分组 id 重复：{g['id']}")
        group_ids.add(g["id"])
        if not isinstance(g.get("item_ids"), list) or g.get("count") != len(g["item_ids"]):
            errors.append(f"分组 {g['id']} 的 count 与 item_ids 数量不一致")
    item_group = {}
    prev_line = -1
    for item in items:
        if not isinstance(item, dict):
            errors.append("items 中的每一项必须是对象")
            continue
        ident = item.get("id")
        if not isinstance(ident, str) or not ident:
            errors.append("item 缺少 id")
            continue
        if ident in seen:
            errors.append(f"item id 重复：{ident}")
        seen.add(ident)
        if item.get("kind") not in ALLOWED_KINDS:
            errors.append(f"{ident} 的 kind 非法：{item.get('kind')!r}")
        if item.get("category") not in ALLOWED_CATEGORIES:
            errors.append(f"{ident} 的 category 非法：{item.get('category')!r}")
        if not isinstance(item.get("line_start"), int) or not isinstance(item.get("line_end"), int):
            errors.append(f"{ident} 缺少有效 line_start/line_end")
        elif item["line_start"] < prev_line:
            errors.append(f"{ident} 未按正文行号顺序排列")
        else:
            prev_line = item["line_start"]
        gid = item.get("group_id")
        if gid not in group_ids:
            errors.append(f"{ident} 的 group_id 不存在：{gid!r}")
        else:
            item_group.setdefault(gid, []).append(ident)
    for g in groups:
        if not isinstance(g, dict) or "id" not in g:
            continue
        listed = set(g.get("item_ids") or [])
        actual = set(item_group.get(g["id"], []))
        if listed != actual:
            errors.append(f"分组 {g['id']} 的 item_ids 与 item.group_id 不一致")
    # Coverage: every table/Mermaid/physical module block must be represented.
    expected = {
        "table": len(parse_tables(text.splitlines())),
        "diagram": len(parse_diagrams(text.splitlines())),
        "module": len(parse_modules(text.splitlines(), md.parent)),
    }
    actual = Counter(x.get("kind") for x in items if isinstance(x, dict))
    for kind, count in expected.items():
        if actual.get(kind, 0) != count:
            errors.append(f"{kind} 覆盖不完整：正文 {count} 个，索引 {actual.get(kind, 0)} 个")
    report["coverage"] = {"expected": expected, "indexed": dict(actual)}
    report["status"] = "FAIL" if errors else ("WARN" if warnings else "PASS")
    return report


def main():
    ap = argparse.ArgumentParser(description="生成 content-index.json v1（仅分类，不渲染网站）")
    ap.add_argument("markdown")
    ap.add_argument("--out", dest="out", default=None)
    ap.add_argument("--report", dest="report", default=None)
    args = ap.parse_args()
    md = Path(args.markdown).expanduser().resolve()
    out = Path(args.out) if args.out else md.parent / "content-index.json"
    try:
        data = build_index(md)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", "utf-8")
        check = check_content_index(md, out)
        payload = {"status": check["status"], "index": str(out),
                   "summary": data["summary"], "warnings": data["warnings"] + check.get("warnings", []),
                   "errors": check.get("errors", [])}
        if args.report:
            Path(args.report).parent.mkdir(parents=True, exist_ok=True)
            Path(args.report).write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", "utf-8")
    except (OSError, UnicodeError) as exc:
        print(json.dumps({"status": "FAIL", "error": str(exc)}, ensure_ascii=False))
        return 2
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return 0 if payload["status"] in ("PASS", "WARN") else 1


if __name__ == "__main__":
    raise SystemExit(main())