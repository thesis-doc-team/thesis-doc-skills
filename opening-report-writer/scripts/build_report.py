#!/usr/bin/env python3
"""Fill only editable slots in the byte-preserved Tarim University DOCX template.

No prose is generated by this script. Agent must supply grounded, referenced JSON.
Dependencies: Python stdlib + lxml (also shipped with python-docx).
"""
from __future__ import annotations
import argparse
import copy
import hashlib
import json
import re
import sys
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from lxml import etree

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / 'assets' / 'official-opening-report-template.docx'
SHA_FILE = ROOT / 'assets' / 'template.sha256'
NS = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
N = {'w': NS}
Q = lambda tag: f'{{{NS}}}{tag}'
CITE_RE = re.compile(r'\[\[cite:([0-9,\-\s]+)\]\]')
RAW_CITE_RE = re.compile(r'(?<!\[)\[(?:\d+)(?:\s*[-,]\s*\d+)*\](?!\])')
COVER_KEYS = {
    '题目': 'title', '学生姓名': 'student_name', '学号': 'student_id',
    '学院': 'college', '专业': 'major', '班级': 'class_name',
    '指导教师': 'supervisor', '职称': 'supervisor_title', '起止时间': 'date_range'
}
DEFAULT_TITLES = [
    '课题研究立项依据', '国内外研究现状及分析',
    '课题任务要求及实现预期目标的可行性分析',
    '重点研究的问题及解决思路', '完成课题所需工作条件及解决办法',
    '工作方案及进度计划', '主要参考文献'
]


def text_of(par):
    return ''.join(par.xpath('.//w:t/text()', namespaces=N))


def normalize_label(s):
    return re.sub(r'[\s\u3000:：]', '', s)


def checked_source(template):
    b = template.read_bytes()
    expected = SHA_FILE.read_text(encoding='utf-8').strip()
    if hashlib.sha256(b).hexdigest() != expected:
        raise ValueError('模板 SHA256 与内置官方原件不符：禁止继续写作。')
    return b


def node(parent, tag, **attrs):
    return etree.SubElement(parent, Q(tag), {Q(k): str(v) for k, v in attrs.items()})


def run(p, text, *, bold=False, superscript=False):
    r = node(p, 'r')
    rp = node(r, 'rPr')
    node(rp, 'rFonts', ascii='Times New Roman', hAnsi='Times New Roman', eastAsia='宋体', cs='Times New Roman')
    if bold:
        node(rp, 'b')
    node(rp, 'sz', val='21')
    node(rp, 'szCs', val='21')
    if superscript:
        node(rp, 'vertAlign', val='superscript')
    t = node(r, 't')
    t.text = text
    if text[:1].isspace() or text[-1:].isspace():
        t.set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    return r


def format_p(p, *, kind='paragraph'):
    pp = node(p, 'pPr')
    node(pp, 'spacing', line='360', lineRule='auto', before='0', after='0')
    node(pp, 'widowControl')
    if kind == 'paragraph':
        node(pp, 'ind', firstLine='420')  # 五号宋体首行约2个汉字（21pt）
    elif kind == 'reference':
        node(pp, 'ind', left='420', hanging='420')  # 参考文献多行悬挂缩进
        node(pp, 'jc', val='left')  # 显式左对齐：两端对齐会在长 URL 外文条目上拉伸出行内大空隙
        node(pp, 'keepLines')  # 尽量将同一条文献放在同一页
    elif kind.startswith('heading'):
        node(pp, 'keepNext')
    return p


def append_inline(p, value, count):
    """Recognize only [[cite:...]] as a superscript citation."""
    if RAW_CITE_RE.search(CITE_RE.sub('', value)):
        raise ValueError('发现裸引用 [n]：请改为 [[cite:n]]，以确保真正 Word 上标。')
    pos = 0
    for m in CITE_RE.finditer(value):
        if m.start() > pos:
            run(p, value[pos:m.start()])
        group = m.group(1).replace(' ', '')
        ids = []
        for token in group.split(','):
            if '-' in token:
                a, b = map(int, token.split('-'))
                if a < 1 or b < a or b - a > 50:
                    raise ValueError('无效引用范围：'+token)
                ids += list(range(a,b+1))
            else:
                ids.append(int(token))
        if any(x < 1 or x > count for x in ids):
            raise ValueError(f'正文引用 {group} 超出参考文献 1..{count}')
        run(p, f'[{group}]', superscript=True)
        pos = m.end()
    if pos < len(value):
        run(p, value[pos:])


def make_para(kind, content, count):
    p = etree.Element(Q('p'))
    format_p(p, kind=kind)
    if kind.startswith('heading'):
        run(p, content, bold=True)
    elif kind == 'reference':
        run(p, content)  # baseline [n] is mandatory in the bibliography
    else:
        append_inline(p, content, count)
    return p


def insert_body(tr, payload):
    """Replace only empty writing-area placeholders in official table row 1.

    Official note, student signature/date, table cell, teacher-opinion row are immutable.
    """
    tc = tr.xpath('./w:tc', namespaces=N)[0]
    ps = tc.xpath('./w:p', namespaces=N)
    note = ps[0]
    signature = [i for i,p in enumerate(ps) if text_of(p).strip().startswith('学生签名')]
    if len(signature) != 1 or signature[0] < 3:
        raise ValueError('官方模板正文签名锚点不匹配：停止。')
    sig_idx = signature[0]
    if '开题报告正文' not in text_of(note):
        raise ValueError('正文表格提示行丢失：停止。')
    writing_slots = ps[1:sig_idx]
    if any(text_of(p).strip() for p in writing_slots):
        raise ValueError('官方模板正文留白区域不是空的：停止，避免覆盖原有资料。')
    # Deleting unused empty lines is limited to the blank *writing area*;
    # fixed official content, signatures, other rows and template remain untouched.
    for p in writing_slots:
        tc.remove(p)
    ref_count = len(payload['references'])
    paragraphs = []
    for i, sec in enumerate(payload['sections'], start=1):
        title = sec.get('title', DEFAULT_TITLES[i-1]).strip()
        if title != DEFAULT_TITLES[i-1] and not payload.get('allow_custom_heading_titles', False):
            raise ValueError(f'第 {i} 章标题与统一预设不符；若用户明确授权请设 allow_custom_heading_titles=true')
        paragraphs.append(make_para('heading1', f'{i} {title}', ref_count))
        if i == 7:
            for n, ref in enumerate(payload['references'], 1):
                content = ref['text'].strip()
                if re.match(r'^\[\d+\]', content):
                    raise ValueError('参考文献 text 不要包含 [n]，生成器只添加一次编号。')
                p = make_para('reference', f'[{n}] {content}', ref_count)
                paragraphs.append(p)
            continue
        blocks = sec.get('blocks') or []
        if not blocks: raise ValueError(f'第 {i} 章没有内容')
        for b in blocks:
            kind = b.get('type','paragraph')
            if kind in {'paragraph', 'heading2', 'heading3'}:
                v = b.get('text','').strip()
                if not v: raise ValueError(f'第{i}章有空文本块')
                paragraphs.append(make_para(kind, v, ref_count))
            elif kind == 'schedule':
                entries = b.get('items', [])
                if not entries: raise ValueError('进度安排为空')
                for e in entries:
                    st, en = int(e['start_week']), int(e['end_week'])
                    if not (1 <= st <= en <= 104):
                        raise ValueError('周次应为 1..104 且开始≤结束')
                    task = str(e['task']).strip()
                    if re.search(r'[～~〜—–]', task):
                        raise ValueError('计划内容含非规范连接符')
                    lab = f'第{st}周--第{en}周：' if st != en else f'第{st}周：'
                    paragraphs.append(make_para('paragraph', lab + task, ref_count))
            else:
                raise ValueError('未知正文块类型：'+kind)
    # Anchor all new paragraphs immediately before the untouched signature.
    signature_node = ps[sig_idx]
    place = list(tc).index(signature_node)
    for p in paragraphs:
        tc.insert(place, p)
        place += 1
    return len(paragraphs)


def fill_cover(root, cover):
    body = root.xpath('./w:body', namespaces=N)[0]
    used = set()
    for p in body.xpath('./w:p', namespaces=N):
        s=text_of(p)
        if '：' not in s or s.strip().startswith('三、'): continue
        label=normalize_label(s.split('：',1)[0])
        if label not in COVER_KEYS: continue
        key=COVER_KEYS[label]
        val=cover.get(key)
        used.add(key)
        if val is None or val == '': continue  # blank stays as the exact official blank
        if not isinstance(val, str) or len(val)>140:
            raise ValueError(f'封面字段 {key} 无效/过长，请手工检查')
        runs=p.xpath('./w:r',namespaces=N)
        if len(runs)<2:
            raise ValueError('封面栏位结构异常：'+label)
        text_elements=runs[-1].xpath('./w:t',namespaces=N)
        if len(text_elements)!=1 or text_elements[0].text is None or text_elements[0].text.strip():
            raise ValueError('封面内容留白已被修改：'+label)
        text_elements[0].text=val
    if set(COVER_KEYS.values()) - used:
        raise ValueError('官方封面字段缺失：'+str(set(COVER_KEYS.values())-used))


def validate_input(data):
    if not isinstance(data, dict): raise ValueError('顶层必须 JSON 对象')
    if len(data.get('sections',[]))!=7:
        raise ValueError('必须提供 7 个一级章节：1..7')
    if len(data.get('references',[]))<10:
        raise ValueError('官方模板规定参考文献不少于 10 篇')
    if not isinstance(data.get('cover',{}), dict):
        raise ValueError('封面字段必须为对象')
    for i, sec in enumerate(data['sections'],1):
        if sec.get('id') != i: raise ValueError(f'章节序号应为 {i}')
    types={'journal','conference','thesis','standard','official_doc','book','blog'}
    for ref in data['references']:
        if ref.get('source_type') not in types:
            raise ValueError('无效参考文献类型 source_type')
        if not isinstance(ref.get('text'),str) or len(ref['text'].strip())<12:
            raise ValueError('每条参考文献至少需要完整出处信息')
        if not ref.get('source_url') and not ref.get('doi'):
            raise ValueError('每条参考文献需要可核查的 source_url 或 DOI')
        if ref.get('source_url'):
            url=str(ref['source_url']).strip()
            if not re.match(r'^https?://\S+',url,re.I):
                raise ValueError('参考文献 URL 必须为可定位的 http(s) 地址')
            if 'csdn.net' in url.lower() and ref['source_type']!='blog':
                raise ValueError('CSDN 来源不可伪装为期刊、标准或官方文档')
        if ref.get('doi') and not re.match(r'^10\.\d{4,9}/\S+',str(ref['doi'])):
            raise ValueError('DOI 格式无效')
        if ref.get('verified') is not True:
            raise ValueError('存在未核查参考文献。必须逐条真实查证并标记 verified=true；禁止虚构。')
    scholarly={'journal','conference','thesis','standard','official_doc','book'}
    if sum(r.get('source_type') in scholarly for r in data['references'])<7:
        raise ValueError('学术论文、学位论文、标准、官方文档等可靠来源应至少占 7 篇')
    if sum(r.get('source_type')=='blog' for r in data['references'])>2:
        raise ValueError('CSDN 等技术博客不得超过 2 篇，不能替代学术文献')


def build(data, template, out):
    validate_input(data)
    if out.exists():
        raise ValueError('成品路径已存在；历史 -vN 文件不得覆盖。请使用新的版本号。')
    checked_source(template)
    with ZipFile(template, 'r') as src:
        root=etree.fromstring(src.read('word/document.xml'))
        rows=root.xpath('./w:body/w:tbl/w:tr',namespaces=N)
        if len(rows)!=2: raise ValueError('官方模板预期 2 行正文/教师意见表格')
        fill_cover(root, data.get('cover',{}))
        n=insert_body(rows[0], data)
        newdoc=etree.tostring(root,xml_declaration=True,encoding='UTF-8',standalone=True)
        if template.resolve()==out.resolve(): raise ValueError('绝对禁止覆盖官方模板原件')
        out.parent.mkdir(parents=True,exist_ok=True)
        with ZipFile(out, 'w') as dest:
            for info in src.infolist():
                b = newdoc if info.filename == 'word/document.xml' else src.read(info.filename)
                dest.writestr(copy.copy(info), b)
    return n


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('report_json', type=Path, help='AI 生成的报告内容 JSON（只含有据的文字）')
    ap.add_argument('--output', required=True, type=Path)
    ap.add_argument('--template', type=Path, default=TEMPLATE)
    args=ap.parse_args()
    try:
        data=json.loads(args.report_json.read_text(encoding='utf-8'))
        n=build(data,args.template,args.output)
        print(f'OK: {args.output}；新增正文段落 {n}；源模板未改写')
    except Exception as exc:
        print(f'FAIL: {exc}', file=sys.stderr)
        sys.exit(1)

if __name__=='__main__': main()
