"""Render-chain regression: --pdf passthrough must work without any office suite.

Fake PDFs are generated by PyMuPDF; nothing here is a real deliverable.
"""
import importlib.util
import sys
import tempfile
import unittest
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BASE / 'scripts'))

HAS_FITZ = importlib.util.find_spec('fitz') is not None


@unittest.skipUnless(HAS_FITZ, 'PyMuPDF 未安装：渲染测试跳过（不虚假验收）')
class TestRenderPdfPassthrough(unittest.TestCase):
    def test_external_pdf_passthrough(self):
        import fitz
        from render_visual import render
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            src = d / 'fake.docx'
            src.write_bytes(b'NOT A REAL DOCX')
            pdf = d / 'ext.pdf'
            doc = fitz.open()
            doc.new_page()
            doc[0].insert_text((72, 72), 'smoke')
            doc.save(str(pdf))
            doc.close()
            out = d / 'png'
            result = render(src, out, pdf_in=pdf)
            self.assertEqual(result.get('converter'), 'external-pdf')
            self.assertTrue((out / 'page-1.png').is_file())

    def test_missing_external_pdf_fails_honestly(self):
        from render_visual import render
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            src = d / 'fake.docx'
            src.write_bytes(b'X')
            with self.assertRaises(ValueError):
                render(src, d / 'png', pdf_in=d / 'nope.pdf')

    def test_deliverables_outdir_still_rejected(self):
        import fitz
        from render_visual import render
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            src = d / 'fake.docx'
            src.write_bytes(b'X')
            pdf = d / 'ext.pdf'
            doc = fitz.open()
            doc.new_page()
            doc.save(str(pdf))
            doc.close()
            with self.assertRaises(ValueError):
                render(src, d / 'deliverables' / 'png', pdf_in=pdf)

    def test_blank_page_detection_and_fail_status(self):
        # 用户要求：Word 成品不得出现空白页——任意页空白检测，渲染预检必须 FAIL_PRECHECK
        import fitz
        from render_visual import render, blank_page_kind
        doc = fitz.open()
        self.assertEqual(blank_page_kind(doc.new_page()), 'blank')
        num = doc.new_page(); num.insert_text((72, 72), '- 2 -')
        self.assertEqual(blank_page_kind(num), 'blank')
        ok = doc.new_page(); ok.insert_text((72, 72), '开题报告正文内容示例，用于验证正常页不被误判为空白页。')
        self.assertIsNone(blank_page_kind(ok))
        doc.close()
        proc_doc = fitz.open()
        c = proc_doc.new_page(); c.insert_text((72, 72), '开题报告正文内容示例，用于验证正常页不被误判为空白页。')
        proc_doc.new_page()
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            pdf = d / 'blank.pdf'; proc_doc.save(str(pdf)); proc_doc.close()
            src = d / 'fake.docx'; src.write_bytes(b'X')
            result = render(src, d / 'png', pdf_in=pdf)
            self.assertEqual(result['status'], 'FAIL_PRECHECK')
            self.assertTrue(any('第2页为空白页' in p for p in result['problems']), result['problems'])


if __name__ == '__main__':
    unittest.main()
