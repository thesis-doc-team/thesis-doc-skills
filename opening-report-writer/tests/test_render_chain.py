"""Render-chain regression: --pdf passthrough must work without any office suite.

Fake PDFs are generated by PyMuPDF; nothing here is a real deliverable.
"""
import importlib.util
import sys
import tempfile
import unittest
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BASE / 'scripts'))

HAS_FITZ = importlib.util.find_spec('fitz') is not None


@unittest.skipUnless(HAS_FITZ, 'PyMuPDF 未安装：渲染测试跳过（不虚假验收）')
class TestRenderPdfPassthrough(unittest.TestCase):
    def test_external_pdf_passthrough(self):
        import fitz
        from render_visual import render
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            src = d / 'fake.docx'
            src.write_bytes(b'NOT A REAL DOCX')
            pdf = d / 'ext.pdf'
            doc = fitz.open()
            doc.new_page()
            doc[0].insert_text((72, 72), 'smoke')
            doc.save(str(pdf))
            doc.close()
            out = d / 'png'
            result = render(src, out, pdf_in=pdf)
            self.assertEqual(result.get('converter'), 'external-pdf')
            self.assertTrue((out / 'page-1.png').is_file())

    def test_missing_external_pdf_fails_honestly(self):
        from render_visual import render
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            src = d / 'fake.docx'
            src.write_bytes(b'X')
            with self.assertRaises(ValueError):
                render(src, d / 'png', pdf_in=d / 'nope.pdf')

    def test_deliverables_outdir_still_rejected(self):
        import fitz
        from render_visual import render
        with tempfile.TemporaryDirectory() as d:
            d = Path(d)
            src = d / 'fake.docx'
            src.write_bytes(b'X')
            pdf = d / 'ext.pdf'
            doc = fitz.open()
            doc.new_page()
            doc.save(str(pdf))
            doc.close()
            with self.assertRaises(ValueError):
                render(src, d / 'deliverables' / 'png', pdf_in=pdf)


if __name__ == '__main__':
    unittest.main()
